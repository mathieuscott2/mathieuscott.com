// Encrypt a folder of HTML report pages into content/audits/<slug>.json, served behind a password by
// app/audits/[...path]/route.ts. The repo is public: only the ciphertext is committed, never the HTML.
//
// Usage (in your own Terminal, so the password never lands anywhere else):
//   node scripts/encrypt-audit.mjs <slug> <folder-with-html-files>
// The password is asked twice with hidden input. Use the same value as AUDIT_PASSWORD in Vercel.
// The file named placement_audit_index_*.html becomes the audit's landing page.
import {createCipheriv, randomBytes, scryptSync} from "node:crypto";
import {readdirSync, readFileSync, writeFileSync, mkdirSync} from "node:fs";
import {join, resolve} from "node:path";

const [slug, dir] = process.argv.slice(2);
if (!slug || !dir || !/^[a-z0-9-]+$/.test(slug)) {
  console.error("usage: node scripts/encrypt-audit.mjs <slug, e.g. youtube-2026-10-22> <folder>");
  process.exit(1);
}

function ask(prompt) {
  // Hidden input on a terminal; plain stdin otherwise.
  return new Promise((done) => {
    const stdin = process.stdin;
    process.stdout.write(prompt);
    if (!stdin.isTTY) {
      let buf = "";
      stdin.on("data", (d) => (buf += d)).on("end", () => done(buf.split("\n")[0]));
      return;
    }
    let value = "";
    stdin.setRawMode(true);
    stdin.resume();
    stdin.setEncoding("utf8");
    const onData = (ch) => {
      if (ch === "\r" || ch === "\n") {
        stdin.setRawMode(false); stdin.pause(); stdin.off("data", onData);
        process.stdout.write("\n"); done(value);
      } else if (ch === "\u0003") process.exit(1);
      else if (ch === "\u007f") value = value.slice(0, -1);
      else value += ch;
    };
    stdin.on("data", onData);
  });
}

const password = await ask("Audit password (same as AUDIT_PASSWORD in Vercel): ");
if (process.stdin.isTTY && (await ask("Again: ")) !== password) {
  console.error("Passwords don't match."); process.exit(1);
}
if (password.length < 12) { console.error("Use at least 12 characters."); process.exit(1); }

const salt = randomBytes(16);
const key = scryptSync(password, salt, 32);
const files = {};
for (const name of readdirSync(dir).filter((f) => f.endsWith(".html")).sort()) {
  let html = readFileSync(join(dir, name), "utf8");
  // Links between pages become absolute, so they work whether or not the URL ends with a slash.
  html = html.replace(/href="(placement_audit_[^"/]+\.html)"/g, `href="/audits/${slug}/$1"`);
  const iv = randomBytes(12);
  const cipher = createCipheriv("aes-256-gcm", key, iv);
  const data = Buffer.concat([cipher.update(html, "utf8"), cipher.final()]);
  files[/^placement_audit_index_/.test(name) ? "index.html" : name] = {
    iv: iv.toString("base64"), tag: cipher.getAuthTag().toString("base64"), data: data.toString("base64"),
  };
}
if (!files["index.html"]) { console.error("No placement_audit_index_*.html in that folder."); process.exit(1); }

const out = resolve("content/audits");
mkdirSync(out, {recursive: true});
writeFileSync(join(out, `${slug}.json`), JSON.stringify({v: 1, kdf: "scrypt", salt: salt.toString("base64"), files}));

// Regenerate the registry the route imports from (one static import per audit, so the bundler ships them).
const slugs = readdirSync(out).filter((f) => f.endsWith(".json")).map((f) => f.slice(0, -5)).sort();
const id = (s) => "a_" + s.replace(/-/g, "_");
writeFileSync(join(out, "registry.ts"),
  "// Generated by scripts/encrypt-audit.mjs. Encrypted audits only; never import plain HTML here.\n" +
  slugs.map((s) => `import ${id(s)} from "./${s}.json";`).join("\n") +
  `\nimport type {AuditBundle} from "./types";\n\nexport const AUDITS: Record<string, AuditBundle> = {${
    slugs.map((s) => `\n  "${s}": ${id(s)},`).join("")}\n};\n`);
console.log(`Encrypted ${Object.keys(files).length} pages into content/audits/${slug}.json`);
